def show_progress_bar():
    print("\nProcessing and Merging Images...")
    toolbar_width = 30
    sys.stdout.write("[%s]" % (" " * toolbar_width))
    sys.stdout.flush()
    sys.stdout.write("\b" * (toolbar_width + 1))

    for i in range(toolbar_width):
        time.sleep(0.05)
        sys.stdout.write("█")
        sys.stdout.flush()

    sys.stdout.write("] 100%\n\n")

def main():
    print_banner()
    print("=== Auto Barcode Merger - Dr. Andro ===\n")
    
    template_path = input("Drag or enter template image path: ").strip().strip('"')
    if not os.path.exists(template_path):
        print("Error: Template image path does not exist!")
        return

    barcode_path = input("Drag or enter barcode image path: ").strip().strip('"')
    if not os.path.exists(barcode_path):
        print("Error: Barcode image path does not exist!")
        return

    try:
        padding = 15
        
        template = Image.open(template_path).convert("RGBA")
        barcode = Image.open(barcode_path).convert("RGBA")
        
        width, height = template.size
        
        lower_half_y = height // 2
        lower_crop = template.crop((0, lower_half_y, width, height))
        gray_crop = lower_crop.convert("L")
        white_mask = gray_crop.point(lambda p: 255 if p > 240 else 0)
        
        bbox = white_mask.getbbox()
        
        if bbox:
            show_progress_bar()

            root = Tk()
            root.withdraw()
            root.attributes('-topmost', True)

            print("Opening file save dialog...")
            output_path = filedialog.asksaveasfilename(
                title="Select Where to Save Final Image - Dr. Andro",
                defaultextension=".png",
                filetypes=[("PNG Image", "*.png"), ("JPEG Image", "*.jpg")],
                initialfile="nitro_gift_final.png"
            )
            root.destroy()

            if not output_path:
                print("Save operation cancelled by user.")
                return

            left, top, right, bottom = bbox
            top += lower_half_y
            bottom += lower_half_y
            
            box_width = (right - left) - (padding * 2)
            box_height = (bottom - top) - (padding * 2)
            
            barcode_resized = barcode.resize((box_width, box_height), Image.Resampling.LANCZOS)
            
            paste_x = left + padding
            paste_y = top + padding
            
            template.paste(barcode_resized, (paste_x, paste_y), barcode_resized)
            
            template.convert("RGB").save(output_path, quality=95)
            print(f"Success! Image generated and saved to:\n{output_path}\n")
        else:
            print("Error: Could not find the white bounding box in the template image.")
            
    except Exception as e:
        print(f"Fatal Error occurred: {e}")

if __name__ == "__main__":
    main()